package tucker;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.time.LocalDate;
import java.time.LocalTime;
import java.util.ArrayList;
import java.util.List;
import java.util.Optional;

/**
 * Stores deliveries in a hosted PostgreSQL database (e.g. Supabase).
 * The tables are created automatically the first time the app connects. Writes are all-or-nothing
 * transactions.
 */
public class PostgresDeliveryRepository implements DeliveryRepository, AutoCloseable {

    private static final String DELIVERIES_TABLE = """
            CREATE TABLE IF NOT EXISTS deliveries (
                id            BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                delivery_date DATE    NOT NULL,
                delivery_time TIME    NOT NULL,
                customer_name TEXT    NOT NULL,
                address       TEXT    NOT NULL,
                phone         TEXT    NOT NULL DEFAULT '',
                payment_type  TEXT    NOT NULL,
                notes         TEXT    NOT NULL DEFAULT '',
                delivered     BOOLEAN NOT NULL DEFAULT FALSE,
                paid          BOOLEAN NOT NULL DEFAULT FALSE
            )""";

    private static final String ITEMS_TABLE = """
            CREATE TABLE IF NOT EXISTS delivery_items (
                id          BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                delivery_id BIGINT  NOT NULL REFERENCES deliveries(id) ON DELETE CASCADE,
                sort_order  INTEGER NOT NULL,
                material    TEXT    NOT NULL,
                amount      TEXT    NOT NULL,
                price       TEXT    NOT NULL DEFAULT ''
            )""";

    private static final String SELECT_DELIVERIES =
            "SELECT id, delivery_date, delivery_time, customer_name, address, phone, "
                    + "payment_type, notes, delivered, paid FROM deliveries ";

    @FunctionalInterface
    private interface SqlAction {
        void run() throws SQLException;
    }

    private final Connection conn;

    /** Connects to the hosted database (Supabase) and creates the tables if they don't exist yet. */
    public PostgresDeliveryRepository(DatabaseConfig config) {
        this(connect(config), true);
    }

    /**
     * Uses an already-open connection. The tests pass a throwaway in-memory database here, with
     * row level security switched off because that statement is specific to PostgreSQL.
     */
    PostgresDeliveryRepository(Connection connection, boolean enableRowLevelSecurity) {
        this.conn = connection;
        try (Statement st = conn.createStatement()) {
            st.execute(DELIVERIES_TABLE);
            st.execute(ITEMS_TABLE);
            if (enableRowLevelSecurity) {
                // Supabase exposes public tables through its web API; with row level security on and no
                // policies, only this direct database login (which bypasses RLS) can read or write them.
                st.execute("ALTER TABLE deliveries ENABLE ROW LEVEL SECURITY");
                st.execute("ALTER TABLE delivery_items ENABLE ROW LEVEL SECURITY");
            }
        } catch (SQLException e) {
            try { conn.close(); } catch (SQLException ignored) { }
            throw new DatabaseException("Could not set up the database tables: " + e.getMessage(), e);
        }
    }
        /*temporary local database */
    public static PostgresDeliveryRepository local(String filePath) {
        try {
            Connection c = DriverManager.getConnection("jdbc:h2:file:" + filePath + ";MODE=PostgreSQL");
            return new PostgresDeliveryRepository(c, false);
        } catch (SQLException e) {
            throw new DatabaseException("Could not open the local database: " + e.getMessage(), e);
        }
    }

    private static Connection connect(DatabaseConfig config) {
        try {
            return DriverManager.getConnection(config.jdbcUrl(), config.username(), config.password());
        } catch (SQLException e) {
            throw new DatabaseException("Could not connect to the database: " + e.getMessage(), e);
        }
    }

    // ---------- Reading ----------

    @Override
    public List<Delivery> findActiveThrough(LocalDate lastDate) {
        return query("WHERE NOT (delivered AND paid) AND delivery_date <= ?", lastDate);
    }

    @Override
    public List<Delivery> findArchived() {
        return query("WHERE delivered AND paid");
    }

    @Override
    public List<Delivery> findAll() {
        return query("");
    }

    @Override
    public Optional<Delivery> findById(long id) {
        return query("WHERE id = ?", id).stream().findFirst();
    }

    private List<Delivery> query(String where, Object... params) {
        String sql = SELECT_DELIVERIES + where + " ORDER BY delivery_date, delivery_time, id";
        try (PreparedStatement ps = conn.prepareStatement(sql)) {
            for (int i = 0; i < params.length; i++) {
                ps.setObject(i + 1, params[i]);
            }
            List<Delivery> result = new ArrayList<>();
            try (ResultSet rs = ps.executeQuery()) {
                while (rs.next()) {
                    result.add(readDelivery(rs));
                }
            }
            return result;
        } catch (SQLException e) {
            throw new DatabaseException("Could not read deliveries: " + e.getMessage(), e);
        }
    }

    private Delivery readDelivery(ResultSet rs) throws SQLException {
        long id = rs.getLong("id");
        return new Delivery(id,
                rs.getObject("delivery_date", LocalDate.class),
                rs.getObject("delivery_time", LocalTime.class),
                rs.getString("customer_name"),
                rs.getString("address"),
                rs.getString("phone"),
                rs.getString("payment_type"),
                loadItems(id),
                rs.getString("notes"),
                rs.getBoolean("delivered"),
                rs.getBoolean("paid"));
    }

    private List<MaterialLine> loadItems(long deliveryId) throws SQLException {
        List<MaterialLine> items = new ArrayList<>();
        String sql = "SELECT material, amount, price FROM delivery_items WHERE delivery_id = ? ORDER BY sort_order";
        try (PreparedStatement ps = conn.prepareStatement(sql)) {
            ps.setLong(1, deliveryId);
            try (ResultSet rs = ps.executeQuery()) {
                while (rs.next()) {
                    items.add(new MaterialLine(rs.getString("material"), rs.getString("amount"), rs.getString("price")));
                }
            }
        }
        return items;
    }

    // ---------- Writing ----------

    @Override
    public void add(Delivery d) {
        long previousId = d.id();
        try {
            inTransaction(() -> {
                String sql = "INSERT INTO deliveries (delivery_date, delivery_time, customer_name, address, "
                        + "phone, payment_type, notes, delivered, paid) VALUES (?,?,?,?,?,?,?,?,?)";
                try (PreparedStatement ps = conn.prepareStatement(sql, Statement.RETURN_GENERATED_KEYS)) {
                    bind(ps, d);
                    ps.executeUpdate();
                    try (ResultSet keys = ps.getGeneratedKeys()) {
                        keys.next();
                        d.setId(keys.getLong("id"));
                    }
                }
                saveItems(d);
            });
        } catch (RuntimeException e) {
            d.setId(previousId); // the insert was rolled back, so the delivery has no id
            throw e;
        }
    }

    @Override
    public void update(Delivery d) {
        if (d.id() <= 0) {
            throw new IllegalArgumentException("This delivery has not been saved yet, so it can't be updated.");
        }
        inTransaction(() -> {
            String sql = "UPDATE deliveries SET delivery_date=?, delivery_time=?, customer_name=?, address=?, "
                    + "phone=?, payment_type=?, notes=?, delivered=?, paid=? WHERE id=?";
            try (PreparedStatement ps = conn.prepareStatement(sql)) {
                bind(ps, d);
                ps.setLong(10, d.id());
                if (ps.executeUpdate() == 0) {
                    throw new SQLException("There is no delivery with id " + d.id());
                }
            }
            try (PreparedStatement ps = conn.prepareStatement("DELETE FROM delivery_items WHERE delivery_id = ?")) {
                ps.setLong(1, d.id());
                ps.executeUpdate();
            }
            saveItems(d);
        });
    }

    private void bind(PreparedStatement ps, Delivery d) throws SQLException {
        ps.setObject(1, d.date());
        ps.setObject(2, d.time());
        ps.setString(3, d.customerName());
        ps.setString(4, d.address());
        ps.setString(5, d.phone() == null ? "" : d.phone());
        ps.setString(6, d.paymentType());
        ps.setString(7, d.notes());
        ps.setBoolean(8, d.isDelivered());
        ps.setBoolean(9, d.isPaid());
    }

    private void saveItems(Delivery d) throws SQLException {
        String sql = "INSERT INTO delivery_items (delivery_id, sort_order, material, amount, price) VALUES (?,?,?,?,?)";
        try (PreparedStatement ps = conn.prepareStatement(sql)) {
            int order = 0;
            for (MaterialLine m : d.items()) {
                ps.setLong(1, d.id());
                ps.setInt(2, order++);
                ps.setString(3, m.name());
                ps.setString(4, m.amount());
                ps.setString(5, m.price());
                ps.executeUpdate();
            }
        }
    }

    /** Runs the action as one all-or-nothing transaction. */
    private void inTransaction(SqlAction action) {
        try {
            conn.setAutoCommit(false);
            try {
                action.run();
                conn.commit();
            } catch (SQLException | RuntimeException e) {
                conn.rollback();
                throw e;
            } finally {
                conn.setAutoCommit(true);
            }
        } catch (SQLException e) {
            throw new DatabaseException("Could not save to the database: " + e.getMessage(), e);
        }
    }

    @Override
    public void close() {
        try {
            conn.close();
        } catch (SQLException e) {
            throw new DatabaseException("Could not close the database", e);
        }
    }
}
